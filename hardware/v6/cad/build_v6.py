def grams_est(m, rho, shell=1.2, infill=0.15):
    """solid grams and printed estimate: ~3 walls (1.2 mm shell over the whole surface) + 15 % infill"""
    V, A = abs(m.volume) / 1000.0, m.area * shell / 1000.0
    sh = min(V, A)
    return round(V * rho, 1), round((sh + infill * (V - sh)) * rho, 1)


def _variants(m):
    yield m
    for digits in (5, 4):
        c = m.copy()
        c.merge_vertices(digits_vertex=digits)
        c.update_faces(c.nondegenerate_faces(height=1e-6))
        c.remove_unreferenced_vertices()
        if not c.is_watertight:
            trimesh.repair.fill_holes(c)
        if c.is_watertight:
            c.fix_normals()
            yield c


def clean(m):
    """STL is float32: pick the variant whose STL reloads as a watertight volume"""
    for c in _variants(m):
        c.export(SCRATCH + '_probe.stl')
        if trimesh.load(SCRATCH + '_probe.stl').is_watertight:
            return c
    print('  WARNING: no watertight export variant found, exporting as built')
    return m


