def below(z):
    return box(-BIG, BIG, -BIG, BIG, -BIG, z)


def above(z):
    return box(-BIG, BIG, -BIG, BIG, z, BIG)


def axis_pt(s):
    return A0 + s * DIR


def _align(m, s0, s1):
    T = trimesh.geometry.align_vectors([0, 0, 1], DIR)
    m.apply_transform(T)
    m.apply_translation(axis_pt((s0 + s1) / 2.0))
    return m


def incl_cyl(r, s0, s1, n=160):
    """cylinder on the chute axis between axial stations s0 < s1"""
    return _align(trimesh.creation.cylinder(radius=r, height=s1 - s0, sections=n), s0, s1)


def incl_rev(profile, s0, s1, n=160):
    """revolved (r, s) profile on the chute axis; s measured from s0..s1 (profile s absolute)"""
    p = np.array([(r, s - (s0 + s1) / 2.0) for r, s in profile])
    m = revolve(p, n)
    if m.volume < 0:
        m.invert()
    return _align(m, s0, s1)


def ell_poly(cx, a, b, n=180):
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    return Polygon(np.c_[cx + a * np.cos(t), b * np.sin(t)])


def ell_r(t, a, b):
    return a * b / np.sqrt((b * np.cos(t)) ** 2 + (a * np.sin(t)) ** 2)


def morph_ell(top, z_top, cx, a, b, z_bot, levels=16, n=128):
    """ruled morph from a star-shaped top outline (about its centroid) to a horizontal ellipse (about (cx, 0))"""
    c0 = np.array(top.centroid.coords[0])
    r0 = bd.radial_outline(top, c0, n)
    th = np.linspace(0, 2 * np.pi, n, endpoint=False)
    r1 = ell_r(th, a, b)
    rings = []
    for t in np.linspace(0, 1, levels + 1):
        c = (1 - t) * c0 + t * np.array([cx, 0.0])
        r = (1 - t) * r0 + t * r1
        rings.append(np.c_[c[0] + r * np.cos(th), c[1] + r * np.sin(th), np.full(n, (1 - t) * z_top + t * z_bot)])
    return bd.ruled_solid(rings)


def rot180(p):
    return affinity.rotate(p, 180, origin=(0, 0))


def yprism(poly_xz, y0, y1):
    """prism of a polygon drawn in (x, z) extruded along Y"""
    m = trimesh.creation.extrude_polygon(poly_xz, height=y1 - y0)          # (u=x, v=z, w=y)
    T = np.array([[1, 0, 0, 0], [0, 0, 1, y0], [0, 1, 0, 0], [0, 0, 0, 1]], float)
    m.apply_transform(T)
    if m.volume < 0:
        m.invert()
    return m


def torus(r_c, r_t, z, x=0.0, y=0.0, n=96):
    t = np.linspace(0, 2 * np.pi, 32, endpoint=False)
    prof = np.c_[r_c + r_t * np.cos(t), z + r_t * np.sin(t)]
    m = revolve(prof, n)
    if m.volume < 0:
        m.invert()
    return at(m, x, y)


def screw_m3(x, y, z_head_seat, length, head_up=False, head_d=5.5, head_h=3.0, d=3.0):
    """DIN912-like placeholder: head bears on z_head_seat; shank goes the other way"""
    if head_up:
        return at(U([cyl(d, z_head_seat - length, z_head_seat + 0.01, 24), cyl(head_d, z_head_seat, z_head_seat + head_h, 32)]), x, y)
    return at(U([cyl(d, z_head_seat - 0.01, z_head_seat + length, 24), cyl(head_d, z_head_seat - head_h, z_head_seat, 32)]), x, y)


def polar(r, a):
    return r * math.cos(math.radians(a)), r * math.sin(math.radians(a))


def report(name, m):
    print(f'{name:28s} watertight={m.is_watertight}  volume={m.volume/1000:8.3f} cm3  '
          f'x[{m.bounds[0,0]:.1f},{m.bounds[1,0]:.1f}] y[{m.bounds[0,1]:.1f},{m.bounds[1,1]:.1f}] '
          f'z[{m.bounds[0,2]:.2f},{m.bounds[1,2]:.2f}]  faces={len(m.faces)}')
    assert m.is_watertight and m.volume > 0, name


