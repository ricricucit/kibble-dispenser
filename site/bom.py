#!/usr/bin/env python3
"""
Bought parts ("Pezzi extra") of design v6, in English, Italian and German.

Source: hardware/v6/bom.json (texts and quantities). It is checked against hardware/v6/cad/v6.json:
every hardware line of the design must appear in some item's "match", and an item's quantity must
equal the sum of the v6.json lines it matches.

    python site/bom.py           rewrite docs/BOM.md
    python site/bom.py --check   exit 1 if docs/BOM.md is out of date (CI runs this)

site/build.py imports load() and render_page() to write the site page v6/parts/index.html.
Only the Python standard library is required.
"""
import html
import json
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent
ROOT = SITE.parent
BOM_JSON = ROOT / 'hardware/v6/bom.json'
V6_JSON = ROOT / 'hardware/v6/cad/v6.json'
BOM_MD = ROOT / 'docs/BOM.md'
REPO = 'https://github.com/ricricucit/kibble-dispenser'
LANGS = ('en', 'it', 'de')
LANG_NAMES = {'en': 'English', 'it': 'Italiano', 'de': 'Deutsch'}

UI = {
    'title': {'en': 'Bought parts', 'it': 'Pezzi extra', 'de': 'Zukaufteile'},
    'lead': {'en': 'Everything you buy for the Kibble Dispenser Outdoor v6, besides the printed parts.',
             'it': 'Tutto quello che si compra per il Kibble Dispenser Outdoor v6, oltre ai pezzi stampati.',
             'de': 'Alles, was man für den Kibble Dispenser Outdoor v6 neben den Druckteilen kauft.'},
    'status': {'en': 'Design v6 is designed, not yet printed or tested: quantities can still change.',
               'it': 'Il progetto v6 è disegnato ma non ancora stampato né provato: le quantità possono ancora cambiare.',
               'de': 'Entwurf v6 ist konstruiert, aber noch nicht gedruckt oder getestet: die Mengen können sich noch ändern.'},
    'source': {'en': 'Quantities and specifications come from the v6 design data. No shop links: buy wherever suits you.',
               'it': 'Quantità e caratteristiche vengono dai dati del progetto v6. Nessun link a negozi: comprate dove preferite.',
               'de': 'Mengen und Angaben stammen aus den Konstruktionsdaten von v6. Keine Shop-Links: kauft, wo es euch passt.'},
    'printed': {'en': 'Printed parts and their files', 'it': 'Pezzi stampati e i loro file', 'de': 'Druckteile und ihre Dateien'},
    'model': {'en': '3D model v6', 'it': 'Modello 3D v6', 'de': '3D-Modell v6'},
    'print': {'en': 'Print files', 'it': 'File di stampa', 'de': 'Druckdateien'},
    'home': {'en': 'Project home', 'it': 'Pagina del progetto', 'de': 'Projektseite'},
    'language': {'en': 'Language', 'it': 'Lingua', 'de': 'Sprache'},
    'licence': {'en': 'Text CC BY 4.0, design data CERN-OHL-P-2.0.',
                'it': 'Testo CC BY 4.0, dati di progetto CERN-OHL-P-2.0.',
                'de': 'Text CC BY 4.0, Konstruktionsdaten CERN-OHL-P-2.0.'},
}


def load():
    """Read bom.json and check it against the hardware list of v6.json."""
    bom = json.loads(BOM_JSON.read_text(encoding='utf-8'))
    hw = json.loads(V6_JSON.read_text(encoding='utf-8'))['hardware']
    qty_of = {}
    for h in hw:
        qty_of[h['item']] = qty_of.get(h['item'], 0) + int(h['qty'])
    matched, errors = set(), []
    for g in bom['groups']:
        for it in g['items']:
            for lang in LANGS:
                if not it['item'].get(lang) or not it.get('use', {}).get(lang):
                    errors.append(f"{g['id']}: '{it['item'].get('en')}' has no {lang} text")
            if 'match' not in it:
                continue
            unknown = [m for m in it['match'] if m not in qty_of]
            if unknown:
                errors.append(f"{g['id']}: {unknown} not in v6.json hardware")
                continue
            matched.update(it['match'])
            want = sum(qty_of[m] for m in it['match'])
            if it['qty'] != want:
                errors.append(f"{g['id']}: '{it['item']['en']}' qty {it['qty']}, v6.json says {want}")
    missing = [h['item'] for h in hw if h['item'] not in matched]
    if missing:
        errors.append(f'v6.json hardware lines missing from bom.json: {missing}')
    if errors:
        sys.exit('bom.json does not match v6.json:\n  ' + '\n  '.join(errors))
    return bom


def qty_text(it):
    return f"{it['qty']} ×" if 'qty' in it else ''


# ---------------------------------------------------------------- Markdown
def render_markdown(bom):
    out = ['<!-- Generated by site/bom.py from hardware/v6/bom.json; edit those, then run python site/bom.py -->',
           '',
           '# Bought parts, design v6 / Pezzi extra / Zukaufteile',
           '',
           ' · '.join(f'[{LANG_NAMES[lang]}](#{LANG_NAMES[lang].lower()})' for lang in LANGS),
           '',
           'Website: <https://ricricucit.github.io/kibble-dispenser/v6/parts/>',
           '']
    for lang in LANGS:
        out += [f'## {LANG_NAMES[lang]}', '', f"**{UI['status'][lang]}**", '',
                f"{UI['lead'][lang]} {UI['source'][lang]}", '']
        for g in bom['groups']:
            out += [f"### {g['title'][lang]}", '']
            if g.get('note'):
                out += [g['note'][lang], '']
            for it in g['items']:
                q = qty_text(it)
                out.append(f"- {'**' + q + '** ' if q else ''}{it['item'][lang]}: {it['use'][lang]}")
            out.append('')
        out += [f"{UI['printed'][lang]}: [hardware/v6/](../hardware/v6/README.md)", '']
    return '\n'.join(out).rstrip('\n') + '\n'


# ---------------------------------------------------------------- HTML page
def _spans(texts, tag='span'):
    """One element per language; CSS shows only the current one."""
    return ''.join(f'<{tag} data-l="{lang}" lang="{lang}">{html.escape(texts[lang])}</{tag}>' for lang in LANGS)


def render_page(bom, versions_html=''):
    e = html.escape
    blocks = []
    for lang in LANGS:
        bands = []
        for g in bom['groups']:
            rows = []
            for it in g['items']:
                q = qty_text(it)
                qty = f'<span class="qty">{e(q)}</span>' if q else '<span class="qty tick" aria-hidden="true"></span>'
                rows.append(f'<li>{qty}<div><h3>{e(it["item"][lang])}</h3><p>{e(it["use"][lang])}</p></div></li>')
            note = f'<p>{e(g["note"][lang])}</p>' if g.get('note') else ''
            bands.append(f'<section class="band" id="{e(g["id"])}-{lang}" aria-labelledby="h-{e(g["id"])}-{lang}">'
                         f'<div class="band-head"><h2 id="h-{e(g["id"])}-{lang}">{e(g["title"][lang])}</h2>{note}</div>'
                         f'<ul class="kit">{"".join(rows)}</ul></section>')
        blocks.append(f'<div class="lang-block" data-l="{lang}" lang="{lang}">{"".join(bands)}</div>')
    titles = ' '.join(f'data-title-{lang}="{e(UI["title"][lang])} · Kibble Dispenser v6"' for lang in LANGS)
    switch = ''.join(f'<button type="button" data-set-lang="{lang}" lang="{lang}" aria-pressed="{str(lang == "en").lower()}">'
                     f'{lang.upper()}</button>' for lang in LANGS)
    return f'''<!doctype html>
<html lang="en" data-lang="en" {titles}>
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>{e(UI['title']['en'])} · Kibble Dispenser v6</title>
  <meta name="description" content="{e(UI['lead']['en'])} {e(UI['status']['en'])}">
  <meta name="theme-color" content="#e1e6e5" media="(prefers-color-scheme: light)">
  <meta name="theme-color" content="#121a1f" media="(prefers-color-scheme: dark)">
  <link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Ccircle cx='16' cy='16' r='15' fill='%23ee6a1f'/%3E%3Cpath d='M13.5 13h5l3.5 15h-12z' fill='%23fff'/%3E%3Ccircle cx='16' cy='16' r='2.6' fill='%2326282c'/%3E%3C/svg%3E">
  <link rel="stylesheet" href="../../css/site.css">
  <link rel="stylesheet" href="../../css/parts.css">
  <script src="../../js/lang.js" defer></script>
</head>
<body>
  <header class="masthead">
    <p class="wordmark"><a href="../../">Kibble Dispenser</a></p>
    <nav aria-label="Pages">
      <ul>
        <li><a href="../3d/" data-keep-lang>{_spans(UI['model'])}</a></li>
        <li><a href="../print/" data-keep-lang>{_spans(UI['print'])}</a></li>
        <li><a href="../../" data-keep-lang>{_spans(UI['home'])}</a></li>
        <li class="nav-repo"><a href="{REPO}">GitHub</a></li>
      </ul>
    </nav>
  </header>
  <main>
    <section class="parts-head">
      <div class="lang-switch" role="group" aria-label="Language / Lingua / Sprache">{switch}</div>
      <h1>{_spans(UI['title'])}</h1>
      <p class="lead">{_spans(UI['lead'])}</p>
      <p class="stamp">{_spans(UI['status'])}</p>
      <p class="source">{_spans(UI['source'])}</p>
    </section>
    {''.join(blocks)}
    <section class="parts-foot">
      <p><a href="../print/" data-keep-lang>{_spans(UI['printed'])}</a> · <a href="../3d/" data-keep-lang>{_spans(UI['model'])}</a></p>
      <p class="aside">{_spans(UI['licence'])} <a href="{REPO}/blob/main/hardware/v6/bom.json">bom.json</a></p>
      {versions_html}
    </section>
  </main>
</body>
</html>
'''


def main():
    md = render_markdown(load())
    if '--check' in sys.argv[1:]:
        if not BOM_MD.exists() or BOM_MD.read_text(encoding='utf-8') != md:
            sys.exit('docs/BOM.md is out of date: run python site/bom.py')
        print('docs/BOM.md is up to date')
        return
    BOM_MD.write_text(md, encoding='utf-8')
    print(f'wrote {BOM_MD.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
